#!/usr/bin/env python3
"""Printability and interference checks for the Benairy CAD output.

Checks
  1. every printed part fits the bed (x, y <= bed, z <= bed height)
  2. every mesh is watertight with positive volume
  3. overhang estimate in the print orientation (faces steeper than 45 deg,
     excluding the first layer)
  4. pairwise interference of all parts in the assembly frame, using exact
     mesh booleans (manifold3d). Touching faces give zero volume and pass.
Writes cad/check_report.md and cad/check_report.json. Exit code 1 on failure.
"""
from __future__ import annotations

import itertools
import json
import os
import sys

import numpy as np
import trimesh

HERE = os.path.dirname(os.path.abspath(__file__))
BED = 256.0
BED_Z = 256.0
MIN_INTERSECT_MM3 = 1.0     # anything above this is a real overlap
OVERHANG_DEG = 45.0

# Pairs that are allowed to overlap (same physical part at two stack
# positions, or envelopes that are meant to sit inside printed pockets)
ALLOWED = set()


def load(path):
    m = trimesh.load(path, force="mesh")
    if not m.is_watertight:
        m.merge_vertices()
        trimesh.repair.fix_normals(m)
    return m


def overhang_fraction(m, deg=OVERHANG_DEG):
    n = m.face_normals
    a = m.area_faces
    cosl = np.cos(np.radians(90 - deg))     # normal pointing down more than 45 deg
    down = n[:, 2] < -cosl
    # exclude faces on the first layer (bottom)
    zmin = m.bounds[0][2]
    fz = m.triangles[:, :, 2].max(axis=1)
    bottom = fz < zmin + 0.3
    sel = down & ~bottom
    return float(a[sel].sum() / a.sum()), float(a[sel].sum())


def main():
    manifest = json.load(open(os.path.join(HERE, "manifest.json")))
    parts = manifest["parts"]
    report = {"bed": BED, "parts": {}, "interference": [], "ok": True}
    lines = ["# CAD check report (generated by cad/check_cad.py)\n",
             "| Part | Qty | Print size x,y,z (mm) | Fits 256 bed | Watertight | Overhang area >45 deg | Note |",
             "|---|---|---|---|---|---|---|"]
    asm = {}
    for name, info in parts.items():
        apath = os.path.join(HERE, "assembly_stl", name + ".stl")
        am = load(apath)
        asm[name] = am
        rec = {"watertight": bool(am.is_watertight), "volume_mm3": float(am.volume)}
        if not info["reference"]:
            pm = load(os.path.join(HERE, "stl", name + ".stl"))
            ext = pm.extents
            fits = bool(ext[0] <= BED + 1e-6 and ext[1] <= BED + 1e-6 and ext[2] <= BED_Z + 1e-6)
            frac, area = overhang_fraction(pm)
            rec.update({"print_extents": [round(float(v), 2) for v in ext], "fits_bed": fits,
                        "watertight": bool(pm.is_watertight), "overhang_fraction": round(frac, 4),
                        "overhang_area_mm2": round(area, 1)})
            if not fits or not pm.is_watertight or pm.volume <= 0:
                report["ok"] = False
            lines.append("| %s | %d | %.1f, %.1f, %.1f | %s | %s | %.1f %% (%.0f mm2) | %s |" % (
                name, info["qty"], ext[0], ext[1], ext[2], "yes" if fits else "**NO**",
                "yes" if pm.is_watertight else "**NO**", 100 * frac, area, info["note"]))
        report["parts"][name] = rec
    # interference
    lines.append("\n## Interference (assembly frame)\n")
    names = list(asm.keys())
    hits = []
    for a, b in itertools.combinations(names, 2):
        if (a, b) in ALLOWED or (b, a) in ALLOWED:
            continue
        if "_pos" in a or "_pos" in b:      # duplicate position references of the same part
            continue
        ca, cb = set(parts[a]["configs"]), set(parts[b]["configs"])
        if "all" not in ca and "all" not in cb and not (ca & cb):
            continue                          # parts of different test configurations
        ma, mb = asm[a], asm[b]
        # fast reject on bounding boxes
        if (ma.bounds[0] > mb.bounds[1] + 1e-6).any() or (mb.bounds[0] > ma.bounds[1] + 1e-6).any():
            continue
        try:
            inter = trimesh.boolean.intersection([ma, mb], engine="manifold")
            vol = float(inter.volume) if inter is not None and len(inter.faces) else 0.0
        except Exception as e:  # pragma: no cover
            vol = -1.0
            hits.append((a, b, vol, "boolean failed: %s" % e))
            continue
        if vol > MIN_INTERSECT_MM3:
            hits.append((a, b, vol, ""))
    if hits:
        lines.append("| Part A | Part B | Overlap volume (mm3) | Note |\n|---|---|---|---|")
        for a, b, v, note in hits:
            lines.append("| %s | %s | %.1f | %s |" % (a, b, v, note))
            report["interference"].append({"a": a, "b": b, "volume_mm3": v, "note": note})
        report["ok"] = False
    else:
        lines.append("No overlaps larger than %.1f mm3 between any two parts. Touching faces are allowed." % MIN_INTERSECT_MM3)
    # clearances of interest
    lines.append("\n## Key clearances\n")
    checks = []
    prm = manifest["params"]
    floor_bot = -prm["ts_half"] - prm["wall"]
    def top_gap(a, plane, note):
        checks.append((a, "floor underside", "z", plane - asm[a].bounds[1][2], note))
    def gap(a, b, axis, note):
        ma, mb = asm[a], asm[b]
        # signed distance between the two boxes along axis (positive = clear)
        g = max(mb.bounds[0][axis] - ma.bounds[1][axis], ma.bounds[0][axis] - mb.bounds[1][axis])
        checks.append((a, b, "xyz"[axis], g, note))
    gap("ref_fan", "fan_guard", 0, "fan to guard (should touch: 0)")
    top_gap("ref_servo", floor_bot, "servo body to floor underside")
    top_gap("drum", floor_bot, "drum top to floor underside")
    top_gap("ref_as5600", floor_bot, "sensor board top to floor underside")
    top_gap("platform", floor_bot, "platform (hanger) top to floor underside")
    gap("ref_lift_cell", "drum", 2, "lift cell top to drum bottom")
    gap("ref_servo", "ref_drag_cell", 0, "servo to drag cell (x)")
    gap("ref_servo", "ref_lift_cell", 2, "servo body to lift cell (z)")
    for a, b, ax, g, note in checks:
        if g < 0.4 and "touch" not in note:
            report["ok"] = False
    lines.append("| A | B | Axis | Gap (mm) | Note |\n|---|---|---|---|---|")
    for a, b, ax, g, note in checks:
        lines.append("| %s | %s | %s | %.2f | %s |" % (a, b, ax, g, note))
        report.setdefault("gaps", []).append({"a": a, "b": b, "axis": ax, "gap_mm": g, "note": note})
    lines.append("\n**Result: %s**\n" % ("PASS" if report["ok"] else "FAIL"))
    with open(os.path.join(HERE, "check_report.md"), "w") as f:
        f.write("\n".join(lines) + "\n")
    with open(os.path.join(HERE, "check_report.json"), "w") as f:
        json.dump(report, f, indent=2)
    print("\n".join(lines))
    return 0 if report["ok"] else 1


if __name__ == "__main__":
    sys.exit(main())
