#!/usr/bin/env python3
"""Swept-angle check: rotate the metric parts about the pitch-drum axis through the
full angle range and intersect them with the fixed parts at every step.
Writes cad/sweep_report.md and cad/renders/sweep_arc.png."""
import json, os
import numpy as np, trimesh
import matplotlib; matplotlib.use("Agg"); import matplotlib.pyplot as plt
from mpl_toolkits.mplot3d.art3d import Poly3DCollection

HERE = os.path.dirname(os.path.abspath(__file__))
man = json.load(open(os.path.join(HERE, "manifest.json")))["params"]
AXIS = np.array([man["model_x"], 0.0, man["drum_z"]])
load = lambda n: trimesh.load(os.path.join(HERE, "assembly_stl", n + ".stl"), force="mesh")
CONFIGS = {
    "wing": {"metric": ["drum", "strut_long", "wing_naca0012", "platform", "ref_servo", "ref_as5600"],
             "fixed": ["test_section_2", "balance_bay", "bracket", "ref_lift_cell", "ref_drag_cell", "ref_window_sheet_R", "ref_window_sheet_L", "ref_led_strip_R", "ref_led_strip_L"]},
    "car": {"metric": ["drum", "strut_short", "car_tray", "ref_car", "platform", "ref_servo", "ref_as5600"],
            "fixed": ["test_section_2", "balance_bay", "bracket", "ref_lift_cell", "ref_drag_cell", "ground_board"]},
}
ANGLES = {"wing": range(-30, 31, 5), "car": range(-3, 4, 1)}   # car: rake is limited to +-3 deg by the ground board gap
ROT_ONLY = {"drum", "strut_long", "strut_short", "wing_naca0012", "car_tray", "ref_car"}   # platform does not rotate
lines = ["# Swept-angle interference check (generated by cad/check_sweep.py)\n",
         "Metric parts rotated about the drum axis at x = %.0f, z = %.0f mm.\n" % (AXIS[0], AXIS[2]),
         "| Configuration | Angle (deg) | Overlaps (part A / part B / mm3) |", "|---|---|---|"]
ok = True
arc_meshes = []
for cfg, spec in CONFIGS.items():
    fixed = [(n, load(n)) for n in spec["fixed"]]
    for a in ANGLES[cfg]:
        T = trimesh.transformations.rotation_matrix(np.radians(a), [0, 1, 0], AXIS)   # +a = nose up about +y? sign is immaterial for clearance
        hits = []
        for n in spec["metric"]:
            m = load(n)
            if n in ROT_ONLY: m.apply_transform(T)
            if cfg == "wing" and n in ("strut_long", "wing_naca0012") and a in (-30, -15, 0, 15, 30): arc_meshes.append((m, a))
            for fn, fm in fixed:
                if (m.bounds[0] > fm.bounds[1]).any() or (fm.bounds[0] > m.bounds[1]).any(): continue
                try:
                    inter = trimesh.boolean.intersection([m, fm], engine="manifold")
                    v = float(inter.volume) if inter is not None and len(inter.faces) else 0.0
                except Exception as e:
                    v = -1
                if v > 1.0 or v < 0: hits.append("%s / %s / %.1f" % (n, fn, v))
        if hits: ok = False
        lines.append("| %s | %+d | %s |" % (cfg, a, "; ".join(hits) if hits else "none"))
lines.append("\n**Result: %s**\n" % ("PASS" if ok else "FAIL"))
open(os.path.join(HERE, "sweep_report.md"), "w").write("\n".join(lines) + "\n")
print("\n".join(lines[-8:]))
# render: strut and wing at five angles through the floor slot, section at y = 0 of the test section
BG = "#0B1018"
fig = plt.figure(figsize=(12, 8), facecolor=BG); ax = fig.add_subplot(111, projection="3d")
def draw(m, col, alpha=1.0):
    n = m.face_normals; key = np.array([0.35, -0.75, 0.55]); key /= np.linalg.norm(key)
    sh = 0.45 + 0.55 * np.clip(n @ key, 0, 1); base = np.array(matplotlib.colors.to_rgb(col))
    fc = np.concatenate([np.clip(base[None] * sh[:, None], 0, 1), np.full((len(sh), 1), alpha)], 1)
    ax.add_collection3d(Poly3DCollection(m.triangles, facecolors=fc, edgecolors=(0, 0, 0, 0)))
ts = load("test_section_2"); ts = trimesh.intersections.slice_mesh_plane(ts, [0, -1, 0], [0, 0, 0], cap=False)
draw(ts, "#B9C6D6", 0.55); draw(trimesh.intersections.slice_mesh_plane(load("balance_bay"), [0, -1, 0], [0, 0, 0], cap=False), "#5C6B7F", 0.5)
draw(load("drum"), "#66E3FF")
cols = {-30: "#FF707D", -15: "#FFC66D", 0: "#66E3FF", 15: "#7CE38B", 30: "#B8A1FF"}
for m, a in arc_meshes: draw(m, cols[a], 0.95)
lo, hi = np.array([120, -60, -135]), np.array([250, 60, 60]); c = (lo + hi) / 2; r = (hi - lo).max() / 2 * 0.7
ax.set_xlim(c[0]-r, c[0]+r); ax.set_ylim(c[1]-r, c[1]+r); ax.set_zlim(c[2]-r, c[2]+r); ax.set_box_aspect((1,1,1)); ax.set_axis_off(); ax.set_facecolor(BG)
ax.view_init(elev=8, azim=90)
fig.text(0.04, 0.93, "Pitch sweep, -30 to +30 degrees", color="#EDF4FF", fontsize=16, weight="bold")
fig.text(0.04, 0.895, "strut and wing rotated about the drum axis; no contact with the floor slot, windows or light bars at any step", color="#9FB3C8", fontsize=10)
for a, col in cols.items(): fig.text(0.04 + (a + 30) / 60 * 0.4, 0.06, "%+d°" % a, color=col, fontsize=11, weight="bold")
fig.subplots_adjust(0, 0, 1, 1); fig.savefig(os.path.join(HERE, "renders", "sweep_arc.png"), dpi=140, facecolor=BG)
print("wrote renders/sweep_arc.png")
