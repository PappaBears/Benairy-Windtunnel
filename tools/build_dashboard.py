#!/usr/bin/env python3
"""Build the dashboard variants from dashboard/index.html and dashboard/demo_sim.js.

  dashboard/index.html   source (with a /*DEMO_SIM*/ placeholder)
  firmware/src/dashboard_html.h   gzip for the ESP32 (simulator script left out to save flash)
  dashboard/standalone.html       index.html with the simulator inlined; open it from disk, it runs by itself
  dashboard/artifact.html         the standalone page without the document wrapper, for publishing
"""
import gzip, os, re
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
D = os.path.join(ROOT, "dashboard")
src = open(os.path.join(D, "index.html")).read()
sim = open(os.path.join(D, "demo_sim.js")).read()
# ESP32: no in-page simulator
esp = src.replace("/*DEMO_SIM*/", "")
gz = gzip.compress(esp.encode(), 9)
out = ["// Generated by tools/build_dashboard.py. Do not edit.", "#pragma once", "#include <pgmspace.h>",
       "#define DASHBOARD_HTML_GZ_LEN %d" % len(gz), "static const uint8_t DASHBOARD_HTML_GZ[] PROGMEM = {"]
for i in range(0, len(gz), 16):
    out.append("  " + ",".join("0x%02x" % b for b in gz[i:i + 16]) + ",")
out.append("};")
open(os.path.join(ROOT, "firmware", "src", "dashboard_html.h"), "w").write("\n".join(out) + "\n")
# standalone
standalone = src.replace("/*DEMO_SIM*/", sim)
open(os.path.join(D, "standalone.html"), "w").write(standalone)
# artifact: strip the document wrapper, keep title + style + body content, force demo, add gutters
m = re.search(r"<title>.*?</title>", standalone, re.S); title = m.group(0)
style = re.search(r"<style>.*?</style>", standalone, re.S).group(0)
body = re.search(r"<body>(.*)</body>", standalone, re.S).group(1)
style = style.replace("html,body{margin:0;", "html,body{margin:0;color-scheme:dark;")
style = style.replace("main{display:grid;", "main{display:grid;padding-left:max(16px,env(safe-area-inset-left,0px));padding-right:max(16px,env(safe-area-inset-right,0px));padding-block:14px;")
body = body.replace("const wantDemo=location.hash==='#demo'||location.protocol==='file:';", "const wantDemo=true;")
art = title + '\n<meta name="claude:viewport-fit-sides" content="cover">\n' + style + "\n" + body
open(os.path.join(D, "artifact.html"), "w").write(art)
print("esp32 gzip %d bytes, standalone %d bytes, artifact %d bytes" % (len(gz), len(standalone), len(art)))
