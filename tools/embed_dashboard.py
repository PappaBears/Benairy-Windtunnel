#!/usr/bin/env python3
"""Gzip dashboard/index.html into firmware/src/dashboard_html.h (PROGMEM array)."""
import gzip, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = open(os.path.join(ROOT, "dashboard", "index.html"), "rb").read()
gz = gzip.compress(src, 9)
out = ["// Generated by tools/embed_dashboard.py. Do not edit.", "#pragma once", "#include <pgmspace.h>",
       "#define DASHBOARD_HTML_GZ_LEN %d" % len(gz), "static const uint8_t DASHBOARD_HTML_GZ[] PROGMEM = {"]
for i in range(0, len(gz), 16):
    out.append("  " + ",".join("0x%02x" % b for b in gz[i:i + 16]) + ",")
out.append("};")
open(os.path.join(ROOT, "firmware", "src", "dashboard_html.h"), "w").write("\n".join(out) + "\n")
print("dashboard: %d bytes -> %d bytes gzip" % (len(src), len(gz)))
